export function Icon({ n, size, style }) {
  const st = size ? { width: size, height: size, ...style } : style;
  return (
    <svg className="i" style={st} aria-hidden="true">
      <use href={`#i-${n}`} />
    </svg>
  );
}

export function Badge({ s, next }) {
  return (
    <span className={`badge ${next ? 'next' : `b-${s.replace(/\s/g, '')}`}`}>{s}</span>
  );
}

